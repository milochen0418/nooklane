JS_KEYS = ("use_board", "use_note", "use_screen", "use_portal", "new_nook", "new_stage", "meeting_empty")


def tr(lang: str, key: str, **params) -> str:
    text = TEXTS.get(lang, TEXTS["en"]).get(key) or TEXTS["en"].get(key, key)
    return text.format(**params) if params else text


def js_strings(lang: str) -> dict[str, str]:
    return {key: tr(lang, key) for key in JS_KEYS}
